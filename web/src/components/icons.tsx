import type { SVGProps } from 'react';

/**
 * Menyu ikonlari.
 *
 * Ilgari Unicode belgilar ishlatilardi (▤ ✉ ☰ ⇶ ↧ ✈ ◈ ⚇ ⚙) — ular har bir
 * tizimda boshqacha ko'rinardi, qismi emoji sifatida rangli chiqardi va
 * o'lchamlari bir xil emas edi. SVG bilan hammasi bir xil qalinlikda va
 * matn rangiga (`currentColor`) moslashib turadi.
 *
 * Uslub: 24×24 katak, faqat chiziq (fill yo'q), qalinlik 1.75, uchlari yumaloq.
 */
type IconProps = SVGProps<SVGSVGElement> & { size?: number };

function Icon({ size = 18, children, ...props }: IconProps) {
  return (
    <svg
      xmlns="http://www.w3.org/2000/svg"
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={1.75}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      {...props}
    >
      {children}
    </svg>
  );
}

